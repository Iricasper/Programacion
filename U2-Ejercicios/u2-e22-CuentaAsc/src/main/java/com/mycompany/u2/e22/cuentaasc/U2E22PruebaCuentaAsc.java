public class U2E22PruebaCuentaAsc {

    public static void main(String[] args) {
        int cont = 1;
        
        System.out.print("Estos son los primeros 100 numeros naturales: ");
        
        while (cont < 100) {
            System.out.print(cont + ", ");
            cont++;
        }
        System.out.print("100.");
    }
}
