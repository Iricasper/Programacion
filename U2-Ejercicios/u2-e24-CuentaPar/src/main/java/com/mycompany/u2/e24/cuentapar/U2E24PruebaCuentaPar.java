package com.mycompany.u2.e24.cuentapar;

public class U2E24PruebaCuentaPar {

    public static void main(String[] args) {
        System.out.print("Estos son los numeros pares hasta el 100: ");

        int cont = 0;

        while (cont < 100) {
            System.out.print(cont + ", ");
            cont++;
            cont++;
        }
        System.out.print("100.");
    }
}
