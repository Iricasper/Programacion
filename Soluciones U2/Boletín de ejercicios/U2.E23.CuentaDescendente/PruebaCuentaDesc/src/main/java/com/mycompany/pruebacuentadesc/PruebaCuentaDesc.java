package com.mycompany.pruebacuentadesc;

public class PruebaCuentaDesc {

    public static void main(String[] args) {
        int contador = 100;
        
        System.out.print("Primeros 100 números naturales: ");
        
        while (contador >= 0) {
            System.out.print(contador + " ");
            contador--;
        }
        
        System.out.println("");
    }
}
