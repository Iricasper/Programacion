package com.mycompany.u2.e23.cuentadesc;

public class U2E23PruebaCuentaDesc {

    public static void main(String[] args) {
        System.out.println("Estos son los numeros desde el 100 hasta el 0: ");
        
        int cont = 100;
        
        while (cont > 0){
            System.out.print(cont + ", ");
            cont--;
        }
        System.out.print("0.");
    }
}
