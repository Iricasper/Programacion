package com.mycompany.u2.e23.cuentadesc;

public class U2E232CuentaDesc {

    public static void main(String[] args) {
        System.out.println("Estos son los numeros desde el 100 hasta el 0: ");
        
        int i;
        
        for (i=100; i>=1; i--) {
            System.out.print(i + ", ");
        }
        
        System.out.println("0.");
    }
}
