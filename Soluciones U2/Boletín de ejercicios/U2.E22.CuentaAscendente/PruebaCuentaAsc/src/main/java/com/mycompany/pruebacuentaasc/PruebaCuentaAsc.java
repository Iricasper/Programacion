package com.mycompany.pruebacuentaasc;

public class PruebaCuentaAsc {

    public static void main(String[] args) {
        int contador = 1;
        
        System.out.print("Primeros 100 números naturales: ");
        
        while (contador <= 100) {
            System.out.print(contador + " ");
            contador++;
        }
        
        System.out.println("");
    }
}
