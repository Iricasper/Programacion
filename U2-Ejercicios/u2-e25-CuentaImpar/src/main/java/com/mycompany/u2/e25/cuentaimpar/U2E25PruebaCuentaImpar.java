package com.mycompany.u2.e25.cuentaimpar;

public class U2E25PruebaCuentaImpar {

    public static void main(String[] args) {
        System.out.print("Estos son los numeros impares hasta el 100: ");

        int cont = 1;

        while (cont < 99) {
            System.out.print(cont + ", ");
            cont++;
            cont++;
        }
        System.out.print("99.");
    }
}
